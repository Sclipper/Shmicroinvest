interface PlanForm {
  depreciationAmount: string;
  nonDepreciableAmount: string;
  acquisitionDate: string;
  startDate: string;
  calcType: 'period' | 'rate';
  annualRate: string;
  activePeriodLength: string;
  conservationOn: boolean;
  conservationStart: string;
  conservationEnd: string;
  manualOn: boolean;
  manualDate: string;
  manualAmount: string;
  /** Hand-edited schedule (null = generated by the server). */
  months: { month: string; amount: string }[] | null;
  regenerate: boolean;
}

interface AssetForm {
  inventoryNumber: string;
  name: string;
  personInCharge: string;
  categoryId: number | null;
  inventoryAccountId: number | null;
  debitAccountId: number | null;
  creditAccountId: number | null;
  locationId: number | null;
  synchronized: boolean;
  note: string;
  serialNumber: string;
  accounting: PlanForm;
  tax: PlanForm;
}

const plainNumber = (v: string) => {
  const t = v.trim();
  if (!t) return '0';
  const d = parseAmount(t);
  return d ? d.toString() : null;
};

const emptyPlan = (date: string, calcType: 'period' | 'rate'): PlanForm => ({
  depreciationAmount: '', nonDepreciableAmount: '', acquisitionDate: date, startDate: date, calcType, annualRate: '', activePeriodLength: calcType === 'period' ? '60' : '',
  conservationOn: false, conservationStart: '', conservationEnd: '', manualOn: false, manualDate: '', manualAmount: '', months: null, regenerate: false,
});

const planFromView = (p: PlanView): PlanForm => ({
  depreciationAmount: p.depreciationAmount.replace('.', ','), nonDepreciableAmount: Number(p.nonDepreciableAmount) ? p.nonDepreciableAmount.replace('.', ',') : '', acquisitionDate: p.acquisitionDate, startDate: p.startDate,
  calcType: p.calcType, annualRate: p.calcType === 'rate' ? String(Number(p.annualRate)) : '', activePeriodLength: p.calcType === 'period' ? String(p.activePeriodLength) : '',
  conservationOn: !!p.conservation, conservationStart: p.conservation?.start ?? '', conservationEnd: p.conservation?.end ?? '',
  manualOn: false, manualDate: '', manualAmount: '', months: null, regenerate: false,
});

const formFromView = (v: AssetView): AssetForm => ({
  inventoryNumber: v.inventoryNumber, name: v.name, personInCharge: v.personInCharge, categoryId: v.categoryId, inventoryAccountId: v.inventoryAccountId,
  debitAccountId: v.debitAccountId, creditAccountId: v.creditAccountId, locationId: v.locationId, synchronized: v.synchronized,
  note: v.accounting.note, serialNumber: v.accounting.serialNumber, accounting: planFromView(v.accounting), tax: planFromView(v.tax),
});

/** Request body (null when an amount cannot be parsed). */
function planBody(p: PlanForm, extra: { note: string; serialNumber: string }) {
  const amount = plainNumber(p.depreciationAmount);
  const non = plainNumber(p.nonDepreciableAmount);
  const rate = p.calcType === 'rate' ? plainNumber(p.annualRate) : null;
  const manual = p.manualOn ? plainNumber(p.manualAmount) : null;
  if (amount === null || non === null || (p.calcType === 'rate' && rate === null) || (p.manualOn && manual === null)) return null;
  if (!p.acquisitionDate || !p.startDate) return null;
  return {
    depreciationAmount: amount, nonDepreciableAmount: non, acquisitionDate: p.acquisitionDate, startDate: p.startDate, calcType: p.calcType,
    annualRate: rate, activePeriodLength: p.calcType === 'period' ? Number(p.activePeriodLength) || 0 : null,
    conservation: p.conservationOn ? { start: p.conservationStart || null, end: p.conservationEnd || null } : null,
    note: extra.note, serialNumber: extra.serialNumber,
    manualAccrued: p.manualOn ? { date: p.manualDate || null, amount: manual } : null,
    months: p.months, regenerate: p.regenerate || undefined,
  };
}

function assetBody(f: AssetForm) {
  const accounting = planBody(f.accounting, f);
  const tax = planBody(f.tax, f);
  if (!accounting || !tax) return null;
  return {
    inventoryNumber: f.inventoryNumber.trim(), name: f.name.trim(), personInCharge: f.personInCharge.trim() || null, categoryId: f.categoryId,
    inventoryAccountId: f.inventoryAccountId, debitAccountId: f.debitAccountId, creditAccountId: f.creditAccountId, locationId: f.locationId,
    synchronized: f.synchronized, accounting, tax,
  };
}

/** Schedule controls: changing them drops a hand-edited grid. */
const SCHEDULE_KEYS: (keyof PlanForm)[] = ['depreciationAmount', 'nonDepreciableAmount', 'startDate', 'calcType', 'annualRate', 'activePeriodLength', 'conservationOn', 'conservationStart', 'conservationEnd', 'manualOn', 'manualDate', 'manualAmount'];

