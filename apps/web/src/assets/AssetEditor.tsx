const STATUS_CLASS: Record<MonthView['status'], string> = {
  normal: '',
  posted: 'bg-emerald-50 text-emerald-800',
  postedDifferent: 'bg-amber-100 text-amber-900',
  readOnly: 'bg-slate-100 text-slate-500',
};

/** Month grid per year (Януари..Декември, % and year sum); editable from FirstEditableMonthDate. */
function Schedule({ view, disabled, onEdit, onReset }: { view: PlanView | undefined; disabled: boolean; onEdit: (months: { month: string; amount: string }[]) => void; onReset: () => void }) {
  const [drafts, setDrafts] = useState<Record<string, string>>({});
  const viewRef = useRef(view);
  viewRef.current = view;
  useEffect(() => setDrafts({}), [view]);
  if (!view) return <div className="mt-3 text-slate-500">Изчисляване…</div>;
  if (view.notApplied || view.months.length === 0) return <div className="mt-3 rounded-sm bg-slate-50 px-3 py-2 text-slate-600">Няма амортизационен план (активът не се амортизира или няма въведени данни).</div>;
  const byMonth = new Map(view.months.map((m) => [m.month, m]));
  const years = [...new Set(view.months.map((m) => Number(m.month.slice(0, 4))))];
  const yearPct = new Map(view.years.map((y) => [y.year, y]));
  const list = () => view.months.map((m) => ({ month: m.month, amount: m.amount }));
  const commit = (month: string) => {
    const v = drafts[month];
    if (v === undefined) return;
    const p = plainNumber(v);
    if (p === null) return;
    const cur = byMonth.get(month);
    if (cur && Number(cur.amount) === Number(p)) return;
    onEdit(list().map((m) => (m.month === month ? { ...m, amount: Number(p).toFixed(2) } : m)));
  };
  const addMonth = () => {
    const last = view.months[view.months.length - 1]!;
    onEdit([...list(), { month: nextMonth(last.month), amount: '0.00' }]);
  };
  const removeLast = () => {
    const last = view.months[view.months.length - 1];
    if (!last || last.status !== 'normal') return;
    onEdit(list().slice(0, -1));
  };
  const lastEditable = view.months[view.months.length - 1]?.status === 'normal';
  return (
    <div className="mt-3">
      <div className="mb-1 flex items-center gap-2">
        <span className="text-[12px] text-slate-600">Амортизационен план по месеци</span>
        <span className="ml-auto flex items-center gap-1.5 text-[11px] text-slate-500">
          <span className="inline-block size-3 rounded-sm bg-emerald-100" /> осчетоводен
          <span className="ml-2 inline-block size-3 rounded-sm bg-amber-200" /> различава се от контирането
          <span className="ml-2 inline-block size-3 rounded-sm bg-slate-200" /> заключен / приключен период
        </span>
      </div>
      <div className="overflow-auto">
        <table className="grid-table" aria-label="Амортизационен план">
          <thead>
            <tr>
              <th>Година</th>
              <th className="text-right">%</th>
              <th className="text-right">Сума</th>
              {MONTH_SHORT.map((m) => (
                <th key={m} className="text-right">
                  {m}
                </th>
              ))}
            </tr>
          </thead>
          <tbody>
            {years.map((y) => (
              <tr key={y}>
                <td className="font-medium">{y}</td>
                <td className="num">{yearPct.get(y) ? Number(yearPct.get(y)!.percentage).toFixed(2).replace('.', ',') : ''}</td>
                <td className="num font-medium">{money(yearPct.get(y)?.amount ?? '0')}</td>
                {MONTH_SHORT.map((_, i) => {
                  const key = `${y}-${String(i + 1).padStart(2, '0')}-01`;
                  const m = byMonth.get(key);
                  if (!m) return <td key={key} className="bg-slate-50" />;
                  const title = m.accountingNumber ? `Контиране № ${m.accountingNumber} от ${bgDate(m.accountingDate)}${m.status === 'postedDifferent' ? ` (осчетоводено ${money(m.postedAmount)})` : ''}` : m.readOnly ? 'Заключен или приключен период' : m.isProcessed ? 'Обработен месец' : 'Неосчетоводен месец';
                  const editable = !disabled && m.status === 'normal';
                  return (
                    <td key={key} className={cx('num p-0!', STATUS_CLASS[m.status])} title={title} data-month={key}>
                      {editable ? (
                        <input
                          className="h-6 w-20 bg-transparent px-1 text-right outline-none focus:bg-white focus:ring-1 focus:ring-brand-500"
                          value={drafts[key] ?? money(m.amount)}
                          onChange={(e) => setDrafts({ ...drafts, [key]: e.target.value })}
                          onBlur={() => commit(key)}
                          onKeyDown={(e) => e.key === 'Enter' && commit(key)}
                          aria-label={`Месец ${monthLabel(key)}`}
                        />
                      ) : (
                        <span className="inline-block w-20 px-1">{money(m.amount)}</span>
                      )}
                    </td>
                  );
                })}
              </tr>
            ))}
          </tbody>
          <tfoot>
            <tr>
              <td colSpan={2}>Общо ({view.months.length} мес.)</td>
              <td className="num">{money(view.total)}</td>
              <td colSpan={12} />
            </tr>
          </tfoot>
        </table>
      </div>
      <div className="mt-2 flex gap-1.5">
        <Button icon={<Plus className="size-3.5" />} onClick={addMonth} disabled={disabled}>
          Добавяне на месец
        </Button>
        <Button icon={<Minus className="size-3.5" />} onClick={removeLast} disabled={disabled || !lastEditable}>
          Премахване на последния месец
        </Button>
        <Button icon={<RotateCcw className="size-3.5" />} onClick={onReset} disabled={disabled}>
          Преизчисляване на плана
        </Button>
      </div>
    </div>
  );
}
