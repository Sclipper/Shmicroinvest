function PlansSummary({ plans, active, onSelect }: { plans: PreviewResult | undefined; active: PlanTab; onSelect: (p: PlanTab) => void }) {
  const lookups = useAssetLookups();
  const rows: [PlanTab, string, PlanView | undefined][] = [['accounting', 'Счетоводен (САП)', plans?.accounting], ['tax', 'Данъчен (ДАП)', plans?.tax]];
  return (
    <table className="grid-table mt-3" aria-label="Амортизационни планове">
      <thead>
        <tr>
          <th>План</th>
          <th className="text-right">Отчетна стойност</th>
          <th className="text-right">Амортизируема ст-ст</th>
          <th>Въведен в експлоатация</th>
          <th>Дата на изхабяване</th>
          <th className="text-right">Срок (мес.)</th>
          <th className="text-right">Год. норма %</th>
          <th>Метод</th>
          <th className="text-right">Начислени амортизации</th>
          <th className="text-right">Остатъчна стойност</th>
          <th>Отписан</th>
        </tr>
      </thead>
      <tbody>
        {rows.map(([k, label, p]) => (
          <tr key={k} aria-selected={k === active} onClick={() => onSelect(k)} className="cursor-default">
            <td className="font-medium">{label}</td>
            <td className="num">{p && money(p.depreciationAmount)}</td>
            <td className="num">{p && money(p.depreciableAmount)}</td>
            <td>{bgDate(p?.startDate)}</td>
            <td>{p?.endDate ? bgDate(p.endDate) : p ? '—' : ''}</td>
            <td className="num">{p?.activePeriodLength || ''}</td>
            <td className="num">{p && Number(p.annualRate) ? Number(p.annualRate).toFixed(2).replace('.', ',') : ''}</td>
            <td>{p ? lookups.data?.methods.find((m) => m.id === p.methodId)?.description : ''}</td>
            <td className="num">{p && money(p.accrued)}</td>
            <td className="num">{p && money(p.remainder)}</td>
            <td>{p?.finalDate ? bgDate(p.finalDate) : p ? 'Неотписан' : ''}</td>
          </tr>
        ))}
      </tbody>
    </table>
  );
}

function PlanFields({ plan, view, disabled, isAccounting, ratePresets, maxRate, onChange }: {
  plan: PlanForm; view: PlanView | undefined; disabled: boolean; isAccounting: boolean; ratePresets: number[]; maxRate?: number; onChange: (p: Partial<PlanForm>) => void;
}) {
  const lookups = useAssetLookups();
  const prefix = isAccounting ? 'sap' : 'dap';
  return (
    <fieldset disabled={disabled} className="grid grid-cols-6 gap-x-3 gap-y-2">
      <Field label="Отчетна стойност">
        <TextInput className="num" name={`${prefix}-amount`} value={plan.depreciationAmount} onChange={(e) => onChange({ depreciationAmount: e.target.value })} />
      </Field>
      <Field label="Неамортизируема стойност">
        <TextInput className="num" value={plan.nonDepreciableAmount} onChange={(e) => onChange({ nonDepreciableAmount: e.target.value })} />
      </Field>
      <Field label="Амортизируема стойност">
        <TextInput className="num" value={view ? money(view.depreciableAmount) : ''} readOnly tabIndex={-1} />
      </Field>
      <Field label="Дата на придобиване">
        <TextInput type="date" value={plan.acquisitionDate} onChange={(e) => onChange({ acquisitionDate: e.target.value })} />
      </Field>
      <Field label="Дата на въвеждане в експлоатация">
        <TextInput type="date" value={plan.startDate} onChange={(e) => onChange({ startDate: e.target.value })} />
      </Field>
      <Field label="Дата на изхабяване">
        <TextInput value={view?.endDate ? bgDate(view.endDate) : ''} readOnly tabIndex={-1} />
      </Field>

      <Field label="Изчисляване по">
        <Select value={plan.calcType} onChange={(e) => onChange({ calcType: e.target.value as 'period' | 'rate', ...(e.target.value === 'rate' && !plan.annualRate && maxRate ? { annualRate: String(maxRate) } : {}), ...(e.target.value === 'period' && !plan.activePeriodLength ? { activePeriodLength: '60' } : {}) })}>
          <option value="period">Полезен срок (месеци)</option>
          <option value="rate">Годишна норма (%)</option>
        </Select>
      </Field>
      {plan.calcType === 'period' ? (
        <Field label="Полезен срок (месеци)">
          <TextInput className="num" type="number" min={0} value={plan.activePeriodLength} onChange={(e) => onChange({ activePeriodLength: e.target.value })} />
        </Field>
      ) : (
        <Field label="Годишна норма (%)" hint={maxRate !== undefined ? `Максимум по ЗКПО: ${maxRate}%` : undefined}>
          <div className="flex gap-1">
            <TextInput className="num" value={plan.annualRate} onChange={(e) => onChange({ annualRate: e.target.value })} />
            <Select className="w-16" value="" onChange={(e) => e.target.value && onChange({ annualRate: e.target.value })} aria-label="Стандартни норми">
              <option value="">…</option>
              {ratePresets.map((r) => (
                <option key={r} value={r}>
                  {r}%
                </option>
              ))}
            </Select>
          </div>
        </Field>
      )}
      <Field label="Метод на амортизация">
        <TextInput value={view ? (lookups.data?.methods.find((m) => m.id === view.methodId)?.description ?? '') : ''} readOnly tabIndex={-1} />
      </Field>
      <Field label="Начислени амортизации">
        <TextInput className="num" value={view ? money(view.accrued) : ''} readOnly tabIndex={-1} />
      </Field>
      <Field label="Остатъчна стойност">
        <TextInput className="num" value={view ? money(view.remainder) : ''} readOnly tabIndex={-1} />
      </Field>
      <Field label={isAccounting ? 'Преоценъчен резерв' : 'Последен обработен месец'}>
        <TextInput className={isAccounting ? 'num' : ''} value={view ? (isAccounting ? money(view.revaluationReserve) : monthLabel(view.lastProcessedDate)) : ''} readOnly tabIndex={-1} />
      </Field>

      <div className="col-span-3 flex flex-wrap items-end gap-2">
        <Checkbox
          label="Консервиране"
          checked={plan.conservationOn}
          onChange={(v) => onChange({ conservationOn: v, regenerate: true, ...(v && !plan.conservationStart && view ? { conservationStart: nextMonth(view.lastProcessedDate) } : {}) })}
        />
        <Field label="От месец">
          <TextInput type="month" className="w-36" value={plan.conservationStart.slice(0, 7)} disabled={!plan.conservationOn} onChange={(e) => onChange({ conservationStart: e.target.value ? `${e.target.value}-01` : '' })} />
        </Field>
        <Field label="До месец (възстановяване)">
          <TextInput type="month" className="w-36" value={plan.conservationEnd.slice(0, 7)} disabled={!plan.conservationOn} onChange={(e) => onChange({ conservationEnd: e.target.value ? `${e.target.value}-01` : '' })} />
        </Field>
      </div>
      <div className="col-span-3 flex flex-wrap items-end gap-2">
        <Checkbox label="Начислени амортизации към дата" checked={plan.manualOn} onChange={(v) => onChange({ manualOn: v })} />
        <Field label="Към дата">
          <TextInput type="date" className="w-36" value={plan.manualDate} disabled={!plan.manualOn} onChange={(e) => onChange({ manualDate: e.target.value })} />
        </Field>
        <Field label="Сума">
          <TextInput className="num w-32" value={plan.manualAmount} disabled={!plan.manualOn} onChange={(e) => onChange({ manualAmount: e.target.value })} />
        </Field>
      </div>
    </fieldset>
  );
}

function nextMonth(iso: string) {
  const [y, m] = iso.split('-').map(Number) as [number, number];
  const d = new Date(Date.UTC(y, m, 1));
  return d.toISOString().slice(0, 10);
}

