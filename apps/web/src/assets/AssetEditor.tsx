type PlanTab = 'accounting' | 'tax';

interface FromPosting { accountingId: number; accountingNumber: string; inventoryAccountId: number; name: string; acquisitionDate: string; startDate: string; depreciationAmount: string }

/** Дълготраен актив: header, both plans (САП / ДАП) and their schedules (spec 03b 6, 07 FixedAssetView / DepreciationView). */
export function AssetEditor({ tab }: ScreenProps) {
  const session = useSession();
  const ws = useWorkspace();
  const dialogs = useDialogs();
  const invalidate = useInvalidate();
  const lookups = useAssetLookups();
  const locations = useLocations();
  const [id, setId] = useState<number | null>((tab.params?.id as number | undefined) ?? null);
  const [form, setForm] = useState<AssetForm | null>(null);
  const [planTab, setPlanTab] = useState<PlanTab>('accounting');
  const [saving, setSaving] = useState(false);
  const [ask, setAsk] = useState<{ text: string; resolve: (v: 'delete' | 'unlink' | null) => void } | null>(null);
  const [improvement, setImprovement] = useState<PlanTab | null>(null);

  const view = useQuery({ queryKey: ['asset', id], queryFn: () => api.get<AssetView>(`/assets/${id}`), enabled: !!id, staleTime: 0 });
  // Created from a posting (strAddFixedAssetData, 03b 14.1): the server prefills it from the entry.
  const fromAccountingId = tab.params?.fromAccountingId as number | undefined;
  const defaults = useQuery({
    queryKey: ['assetNew', tab.key, fromAccountingId],
    queryFn: () => api.get<{ inventoryNumber: string; acquisitionDate: string; startDate: string; isEuro: boolean; fromPosting: FromPosting | null }>(`/assets/new${fromAccountingId ? `?accountingId=${fromAccountingId}` : ''}`),
    enabled: !id,
    staleTime: Infinity,
  });

  useEffect(() => {
    if (id && view.data) setForm(formFromView(view.data));
  }, [id, view.data]);
  useEffect(() => {
    if (!id && defaults.data && !form) {
      const d = defaults.data;
      const fp = d.fromPosting;
      const plan = (calcType: 'period' | 'rate'): PlanForm => (fp
        ? { ...emptyPlan(fp.startDate, calcType), acquisitionDate: fp.acquisitionDate, depreciationAmount: fp.depreciationAmount.replace('.', ',') }
        : emptyPlan(d.startDate, calcType));
      setForm({
        inventoryNumber: d.inventoryNumber, name: fp?.name ?? '', personInCharge: '', categoryId: null, inventoryAccountId: fp?.inventoryAccountId ?? null, debitAccountId: null, creditAccountId: null,
        locationId: (tab.params?.locationId as number | undefined) ?? null, synchronized: false, note: '', serialNumber: '',
        accounting: plan('period'), tax: plan('rate'),
      });
      if (fp) setDirty(true);
    }
  }, [id, defaults.data, form, tab.params]);

  const body = useMemo(() => (form ? assetBody(form) : null), [form]);
  const [debounced, setDebounced] = useState(body);
  useEffect(() => {
    const t = setTimeout(() => setDebounced(body), 250);
    return () => clearTimeout(t);
  }, [body]);
  const preview = useQuery({
    queryKey: ['assetPreview', tab.key, id, view.dataUpdatedAt, JSON.stringify(debounced)],
    queryFn: () => api.post<PreviewResult>('/assets/preview', { ...debounced!, id }),
    enabled: !!debounced,
    placeholderData: keepPreviousData,
    staleTime: Infinity,
    retry: false,
  });

  const terminated = !!view.data?.isTerminated;
  const editable = !terminated;
  const setDirty = (dirty: boolean) => tab.dirty !== dirty && ws.update(tab.key, { dirty });

  const update = (patch: Partial<AssetForm>) => {
    if (!form) return;
    setForm({ ...form, ...patch });
    setDirty(true);
  };
  const updatePlan = (which: PlanTab, patch: Partial<PlanForm>) => {
    if (!form) return;
    const cur = form[which];
    const touchesSchedule = SCHEDULE_KEYS.some((k) => k in patch && patch[k] !== cur[k]);
    const next: PlanForm = { ...cur, ...patch, ...(touchesSchedule && !('months' in patch) ? { months: null } : {}) };
    setForm({ ...form, [which]: next });
    setDirty(true);
  };

  const plans = preview.data;
  const messages: Message[] = plans?.messages ?? [];

  const setCategory = (categoryId: number | null) => {
    if (!form) return;
    const max = categoryId ? lookups.data?.maxRates[categoryId] : undefined;
    const tax = form.tax.calcType === 'rate' && !form.tax.annualRate && max ? { ...form.tax, annualRate: String(max), months: null } : form.tax;
    setForm({ ...form, categoryId, tax });
    setDirty(true);
  };

  const copyToTax = () => {
    if (!form) return;
    const a = form.accounting;
    setForm({ ...form, tax: { ...form.tax, depreciationAmount: a.depreciationAmount, nonDepreciableAmount: a.nonDepreciableAmount, acquisitionDate: a.acquisitionDate, startDate: a.startDate, calcType: a.calcType, annualRate: a.annualRate, activePeriodLength: a.activePeriodLength, conservationOn: a.conservationOn, conservationStart: a.conservationStart, conservationEnd: a.conservationEnd, months: null, regenerate: true } });
    setDirty(true);
    setPlanTab('tax');
  };

  const askPostings = (text: string) => new Promise<'delete' | 'unlink' | null>((resolve) => setAsk({ text, resolve }));

  const save = async (extra: Record<string, unknown> = {}): Promise<void> => {
    if (!form) return;
    const b = assetBody(form);
    if (!b) {
      await dialogs.alert('Въведена е невалидна сума или дата.');
      return;
    }
    setSaving(true);
    try {
      const r = id ? await send<{ id: number; warnings: Message[] }>('PUT', `/assets/${id}`, { ...b, ...extra }) : await send<{ id: number; warnings: Message[] }>('POST', '/assets', { ...b, ...extra });
      await invalidate('assets', 'accountingRequests', 'assetPreview', 'reports');
      if (id) await view.refetch();
      else setId(r.id);
      setDirty(false);
      ws.update(tab.key, { title: `ДА ${b.inventoryNumber}`, params: { id: r.id } });
      if (r.warnings.length) await dialogs.messages('Активът е записан', r.warnings);
    } catch (e) {
      if (e instanceof CodedError && e.status === 409 && e.code === 'postingsDiffer') {
        setSaving(false);
        const choice = await askPostings(e.message);
        if (choice) return save({ ...extra, postingsResolution: choice });
        return;
      }
      if (e instanceof CodedError && e.status === 409 && e.code === 'plansDiffer') {
        setSaving(false);
        if (await dialogs.confirm(e.message)) return save({ ...extra, plansDifferAccepted: true });
        return;
      }
      if (e instanceof CodedError && e.status === 409 && e.code === 'improvements') {
        setSaving(false);
        if (await dialogs.confirm(e.message)) return save({ ...extra, clearImprovements: true });
        return;
      }
      await dialogs.error(e, 'Активът не може да бъде записан');
    } finally {
      setSaving(false);
    }
  };

  const removeImprovement = async (which: PlanTab, impId: number) => {
    if (!id || !(await dialogs.confirm('Желаете ли да премахнете избраното подобрение?'))) return;
    try {
      await api.del(`/assets/${id}/improvements/${impId}`);
      await view.refetch();
      await invalidate('assets');
    } catch (e) {
      await dialogs.error(e);
    }
    void which;
  };

  if (!form || (id && view.isLoading)) {
    return (
      <Empty>
        <Spinner />
      </Empty>
    );
  }

  const plan = planTab === 'accounting' ? form.accounting : form.tax;
  const planView = planTab === 'accounting' ? plans?.accounting : plans?.tax;
  const taxFollows = planTab === 'tax' && form.synchronized;
  const currency = view.data ? (view.data.isEuro ? 'EUR' : 'BGN') : session.baseCurrency;

  return (
    <div className="flex h-full flex-col">
      <CommandBar
        right={
          <span className="flex items-center gap-2 text-[12px] text-slate-500">
            {preview.isFetching && <Spinner className="size-3.5" />}
            {terminated && <span className="font-medium text-red-700">Активът е отписан{view.data?.terminationAccountingNumber ? ` (контиране № ${view.data.terminationAccountingNumber})` : ''}</span>}
            <span>Валута: {currency}</span>
          </span>
        }
      >
        <Button variant="primary" icon={<Save className="size-3.5" />} onClick={() => void save()} disabled={!editable || saving}>
          Запис
        </Button>
        <Button icon={<Copy className="size-3.5" />} onClick={copyToTax} disabled={!editable || form.synchronized} title="Копиране на счетоводния план в данъчния">
          Копиране
        </Button>
      </CommandBar>

      <div className="min-h-0 flex-1 overflow-auto p-3">
        <fieldset disabled={!editable} className="grid grid-cols-4 gap-x-3 gap-y-2">
          <Field label="Наименование" className="col-span-2">
            <TextInput value={form.name} onChange={(e) => update({ name: e.target.value })} autoFocus={!id} />
          </Field>
          <Field label="Инвентарен номер">
            <TextInput value={form.inventoryNumber} onChange={(e) => update({ inventoryNumber: e.target.value })} />
          </Field>
          <Field label="МОЛ">
            <TextInput value={form.personInCharge} onChange={(e) => update({ personInCharge: e.target.value })} />
          </Field>
          <Field label="Местоположение">
            <Select value={form.locationId ?? ''} onChange={(e) => update({ locationId: e.target.value ? Number(e.target.value) : null })}>
              {(locations.data ?? []).map((l) => (
                <option key={l.id} value={l.id}>
                  {'  '.repeat(Math.max(0, l.level - 1))}
                  {l.name}
                </option>
              ))}
            </Select>
          </Field>
          <Field label="Категория по ЗКПО">
            <Select value={form.categoryId ?? ''} onChange={(e) => setCategory(e.target.value ? Number(e.target.value) : null)}>
              <option value="">— изберете —</option>
              {lookups.data?.categories.map((c) => (
                <option key={c.id} value={c.id}>
                  {c.description}
                </option>
              ))}
            </Select>
          </Field>
          <Field label="Сериен номер">
            <TextInput value={form.serialNumber} onChange={(e) => update({ serialNumber: e.target.value })} />
          </Field>
          <Field label="Забележка">
            <TextInput value={form.note} onChange={(e) => update({ note: e.target.value })} />
          </Field>
          <Field label="Активът се води в сметка">
            <AccountPicker value={form.inventoryAccountId} onChange={(a) => update({ inventoryAccountId: a?.id ?? null })} />
          </Field>
          <Field label="Амортизация в сметка">
            <AccountPicker value={form.debitAccountId} onChange={(a) => update({ debitAccountId: a?.id ?? null })} />
          </Field>
          <Field label="Разход за амортизация в сметка">
            <AccountPicker value={form.creditAccountId} onChange={(a) => update({ creditAccountId: a?.id ?? null })} />
          </Field>
          <div className="flex items-end pb-1">
            <Checkbox
              label="Синхронизиране на данъчна и сч. амортизация"
              checked={form.synchronized}
              onChange={(v) => {
                setForm({ ...form, synchronized: v, tax: { ...form.tax, months: null } });
                setDirty(true);
              }}
            />
          </div>
        </fieldset>

        <PlansSummary plans={plans} active={planTab} onSelect={setPlanTab} />

        <div className="mt-3 flex gap-px border-b border-slate-300 text-[12.5px]">
          {([['accounting', 'Счетоводна амортизация (САП)'], ['tax', 'Данъчна амортизация (ДАП)']] as [PlanTab, string][]).map(([k, label]) => (
            <button key={k} onClick={() => setPlanTab(k)} className={cx('rounded-t-sm border border-b-0 px-3 py-1', planTab === k ? 'border-slate-300 bg-white font-medium' : 'border-transparent text-slate-600 hover:bg-slate-200')}>
              {label}
            </button>
          ))}
        </div>
        <div className="rounded-b-sm border border-t-0 border-slate-300 bg-white p-3">
          {taxFollows && <div className="mb-2 rounded-sm bg-brand-50 px-2 py-1 text-[12px] text-brand-700">Данъчният план следва счетоводния (синхронизирани планове).</div>}
          <PlanFields
            plan={plan}
            view={planView}
            disabled={!editable || taxFollows}
            isAccounting={planTab === 'accounting'}
            ratePresets={lookups.data?.ratePresets ?? []}
            maxRate={form.categoryId ? lookups.data?.maxRates[form.categoryId] : undefined}
            onChange={(patch) => updatePlan(planTab, patch)}
          />
          {id && planView && (
            <Improvements
              plan={planView}
              disabled={!editable || taxFollows || !!tab.dirty}
              onAdd={() => setImprovement(planTab)}
              onRemove={(impId) => void removeImprovement(planTab, impId)}
            />
          )}
          <Schedule
            view={planView}
            disabled={!editable || taxFollows}
            onEdit={(months) => updatePlan(planTab, { months })}
            onReset={() => updatePlan(planTab, { months: null, regenerate: true })}
          />
        </div>

        {messages.length > 0 && (
          <ul className="mt-3 flex flex-col gap-1 rounded-sm border border-slate-300 bg-white p-2" aria-label="Съобщения">
            {messages.map((m, i) => (
              <li key={i} className="flex items-start gap-2">
                <span className={m.severity === 'critical' ? 'text-red-600' : 'text-amber-600'}>{m.severity === 'critical' ? '⛔' : '⚠'}</span>
                <span>{m.text}</span>
              </li>
            ))}
          </ul>
        )}
      </div>

      {ask && (
        <Dialog title="Потвърждение" width={560} onClose={() => { ask.resolve(null); setAsk(null); }}
          footer={
            <>
              <Button variant="primary" data-autofocus onClick={() => { ask.resolve('delete'); setAsk(null); }}>Да</Button>
              <Button onClick={() => { ask.resolve('unlink'); setAsk(null); }}>Не</Button>
              <Button onClick={() => { ask.resolve(null); setAsk(null); }}>Отказ</Button>
            </>
          }
        >
          <div className="whitespace-pre-line">{ask.text}</div>
          <div className="mt-2 text-[12px] text-slate-500">„Да“ изтрива контиранията, „Не“ само премахва връзката с тях.</div>
        </Dialog>
      )}
      {improvement && id && planView && (
        <ImprovementDialog
          current={planView.depreciationAmount}
          onClose={() => setImprovement(null)}
          onSubmit={async (amount) => {
            try {
              await api.post(`/assets/${id}/improvements`, { plan: improvement, amount });
              setImprovement(null);
              await view.refetch();
              await invalidate('assets', 'assetPreview');
            } catch (e) {
              await dialogs.error(e, 'Подобрението не може да бъде добавено');
            }
          }}
        />
      )}
    </div>
  );
}

