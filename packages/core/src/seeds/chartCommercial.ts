export interface TemplateAccount {
  number: string;
  description: string;
  categoryId: number | null;
  isActive: boolean | null;
  parentNumber: string;
}

/** Parent number of a template account: drop the last "/n" segment, else the last digit. */
export function templateParent(number: string, separator = '/'): string {
  const i = number.lastIndexOf(separator);
  if (i > 0) return number.slice(0, i);
  return number.length > 1 ? number.slice(0, -1) : '0';
}

export function parseChartTemplate(text: string): TemplateAccount[] {
  return text
    .split('\n')
    .map((l) => l.trim())
    .filter(Boolean)
    .map((line) => {
      const [number, description, cat, nature] = line.split('|');
      return {
        number: number!,
        description: description!,
        categoryId: cat && cat !== 'null' ? Number(cat) : null,
        isActive: nature === 'A' ? true : nature === 'P' ? false : null,
        parentNumber: templateParent(number!),
      };
    });
}
