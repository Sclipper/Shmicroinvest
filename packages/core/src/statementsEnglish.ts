const norm = (s: string) => s.replace(/\s+/g, ' ').trim();
const BY_NORMALIZED = new Map(Object.entries(STATEMENT_CAPTIONS_EN).map(([bg, en]) => [norm(bg), en]));

/**
 * English caption, or the Bulgarian one when there is no translation (e.g. an
 * edited caption). Matching ignores the kind of spaces (the seed has no-break spaces).
 */
export const captionEn = (bg: string) => BY_NORMALIZED.get(norm(bg)) ?? bg;

/** Unit label in English (9.8, 12). */
export function statementUnitEn(endYear: number, thousands: boolean) {
  const cur = endYear > 2025 ? 'EUR' : 'BGN';
  return thousands ? `thousand ${cur}` : cur;
}
